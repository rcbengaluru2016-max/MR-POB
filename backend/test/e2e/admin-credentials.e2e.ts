test('inactive Admin sees its dedicated page, activation permits login, and deactivation blocks existing pages and APIs', async ({page, browser}) => {
  const signIn = async (target: typeof page, username: string) => {
    await target.goto('/login');
    await target.locator('[name="username"]').fill(username);
    await target.locator('[name="password"]:visible').fill(username === 'browser-admin' ? 'BrowserPass123' : 'InitialPass123!');
    await target.getByRole('button', {name: 'LOGIN', exact: true}).click();
  };
  const email = 'inactive-login-admin@example.test';
  await signIn(page, 'browser-admin');
  await expect(page).toHaveURL(/\/super-admin\/dashboard$/);
  await page.goto('/super-admin/users');
  await page.locator('[name="name"]').fill('Inactive Login Admin');
  await page.locator('[name="email"]').fill(email);
  await page.locator('[name="password"]:visible').fill('InitialPass123!');
  await page.locator('[name="initialStatus"]').selectOption('locked');
  await page.getByRole('button', {name: 'Create Account', exact: true}).click();
  const row = page.getByRole('row').filter({hasText: email});
  await expect(row).toContainText('Inactive');
  await page.getByRole('button', {name: 'Logout', exact: true}).click();
  await expect(page).toHaveURL(/\/login$/);
  await signIn(page, email);
  await expect(page).toHaveURL(/\/account-inactive$/);
  await expect(page.getByRole('status')).toHaveText('Your account is currently inactive. Please contact the Super Admin to activate your account.');
  expect((await page.request.get('/api/admin/summary')).status()).toBe(401);
  await page.getByRole('button', {name: 'Back to Login', exact: true}).click();
  await expect(page).toHaveURL(/\/login$/);
  const superContext = await browser.newContext({ baseURL: new URL(page.url()).origin });
  const superPage = await superContext.newPage();
  try {
    await signIn(superPage, 'browser-admin');
    await expect(superPage).toHaveURL(/\/super-admin\/dashboard$/);
    await superPage.goto('/super-admin/users');
    const managedRow = superPage.getByRole('row').filter({hasText: email});
    await managedRow.getByRole('button', {name: /Account is Inactive/}).click();
    await superPage.getByRole('button', {name: 'Set Active', exact: true}).click();
    await expect(managedRow).toContainText('Active');
    await signIn(page, email);
    await expect(page).toHaveURL(/\/admin\/dashboard$/);
    await expect(page.getByLabel('Authenticator code')).toHaveCount(0);
    expect((await page.request.get('/api/super-admin/accounts')).status()).toBe(403);
    await managedRow.getByRole('button', {name: /Account is Active/}).click();
    await superPage.getByRole('button', {name: 'Set Inactive', exact: true}).click();
    await expect(managedRow).toContainText('Inactive');
    await page.goto('/admin/dashboard');
    await expect(page).toHaveURL(/\/account-inactive$/);
    expect((await page.request.get('/api/admin/summary')).status()).toBe(401);
  } finally { await superContext.close(); }
});
